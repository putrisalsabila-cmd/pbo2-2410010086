private void simpan() {
    String kode = kodeField.getText().trim();
    String judul = judulField.getText().trim();
    String penulis = penulisField.getText().trim();
    String tahunTerbit = tahunField.getText().trim();

    // Validasi kode
    if (kode.isEmpty()) {
        pesanLabel.setText("Kode wajib diisi");
        kodeField.requestFocusInWindow();
        return;
    }

    // Validasi judul
    if (judul.isEmpty()) {
        pesanLabel.setText("Judul wajib diisi");
        judulField.requestFocusInWindow();
        return;
    }

    // Validasi tahun tidak boleh kosong
    if (tahunTerbit.isEmpty()) {
        pesanLabel.setText("Tahun terbit wajib diisi");
        tahunField.requestFocusInWindow();
        return;
    }

    // Validasi tahun harus berupa angka
    int tahun;
    try {
        tahun = Integer.parseInt(tahunTerbit);
    } catch (NumberFormatException e) {
        pesanLabel.setText("Tahun harus berupa angka");
        tahunField.requestFocusInWindow();
        return;
    }

    // Validasi rentang tahun
    int tahunSekarang = java.time.Year.now().getValue();

    if (tahun < 1900 || tahun > tahunSekarang) {
        pesanLabel.setText(
            "Tahun harus antara 1900 sampai " + tahunSekarang
        );
        tahunField.requestFocusInWindow();
        return;
    }

    Status status = (Status) statusCombo.getSelectedItem();

    hasil = new Buku(
        kode,
        judul,
        penulis,
        tahunTerbit,
        status
    );

    dispose();
}
 
        
