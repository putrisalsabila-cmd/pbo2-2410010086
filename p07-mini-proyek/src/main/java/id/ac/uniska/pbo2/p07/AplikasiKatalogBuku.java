    private int barisTerpilih() {
        int baris = bukuTable.getSelectedRow();
        if (baris < 0) {
            return -1;
    }
        return bukuTable.convertRowIndexToModel(baris);
    }
    
    private void perbaruiTombol() {
        boolean adaPilihan = bukuTable.getSelectedRow() >= 0;

        ubahButton.setEnabled(adaPilihan);
        hapusButton.setEnabled(adaPilihan);

        ubahItem.setEnabled(adaPilihan);
        hapusItem.setEnabled(adaPilihan);
    }
    
    private void perbaruiStatus() {
        int terlihat = bukuTable.getRowCount();
        int tersedia = 0;

        for (int i = 0; i < terlihat; i++) {
            int barisModel = bukuTable.convertRowIndexToModel(i);

            if (model.get(barisModel).status() == Status.Tersedia) {
                tersedia++;
            }
        }

        statusLabel.setText(
            terlihat + " buku ditampilkan | " +
            tersedia + " buku tersedia"
        );
    }
    
    private void tambah() {
    Buku hasil = new DialogKatalogBuku(
        this, "Tambah Buku", null
    ).tampilkan();

    if (hasil != null) {
        model.tambah(hasil);
        perbaruiStatus();
    }
}
    
    private void ubah() {
    int baris = barisTerpilih();
    if (baris < 0) {
        return;
    }

    
    Buku hasil = new DialogKatalogBuku(
        this, "Ubah Buku", model.get(baris)
    ).tampilkan();

    if (hasil != null) {
        model.ubah(baris, hasil);
        perbaruiStatus();
    }
}
    
    private void hapus() {
    int baris = barisTerpilih();
    if (baris < 0) {
        return;
    }

    int pilihan = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Hapus buku yang dipilih?",
        "Konfirmasi Hapus",
        javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (pilihan == javax.swing.JOptionPane.YES_OPTION) {
        model.hapus(baris);
        perbaruiStatus();
    }
}
    
    private void saring() {
    String kata = cariField.getText().trim();

    if (kata.isEmpty()) {
        sorter.setRowFilter(null);
    } else {
        sorter.setRowFilter(
            RowFilter.regexFilter("(?i)" + Pattern.quote(kata), 0, 1, 2)
        );
    }

    perbaruiStatus();

    }

